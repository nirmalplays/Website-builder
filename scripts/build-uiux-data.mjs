// Extracts the ui-ux-pro-max catalogues into a compact module this app can use.
//
// Source: github.com/nextlevelbuilder/ui-ux-pro-max-skill (MIT), as installed
// at ~/.claude/skills/ui-ux-pro-max. MIT permits redistribution, which is why
// this data is vendored while React Bits component source is not - that one is
// MIT + Commons Clause and is fetched at generation time instead.
//
// Only three of its catalogues are taken, and only the columns that change what
// gets built: a palette and a style recommendation per product type, and the
// font pairings whose faces the preview actually loads. The rest - icon lists,
// per-framework stack notes, chart guidance - is either unusable here or would
// cost more prompt tokens than it earns.
//
// Run: node scripts/build-uiux-data.mjs
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";

const SRC = join(homedir(), ".claude", "skills", "ui-ux-pro-max", "data");
const OUT = "lib/skills/uiuxData.generated.ts";

if (!existsSync(SRC)) {
  console.error(`FAIL: ${SRC} not found. Install the ui-ux-pro-max skill first.`);
  process.exit(1);
}

/** Minimal RFC4180 reader: the source files quote commas inside fields. */
function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = "";
  let quoted = false;

  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"') {
        if (text[i + 1] === '"') { field += '"'; i++; }
        else quoted = false;
      } else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ",") { row.push(field); field = ""; }
    else if (c === "\n") { row.push(field); rows.push(row); row = []; field = ""; }
    else if (c !== "\r") field += c;
  }
  if (field || row.length) { row.push(field); rows.push(row); }

  const [head, ...rest] = rows;
  return rest
    .filter((r) => r.length === head.length && r.some((v) => v.trim()))
    .map((r) => Object.fromEntries(head.map((h, i) => [h.trim(), r[i].trim()])));
}

const read = (f) => parseCsv(readFileSync(join(SRC, f), "utf8"));

// Fonts the preview loads. A pairing naming a face we do not serve would be
// advice the build cannot follow, so those are dropped rather than approximated.
const LOADED = new Set([
  "Playfair Display", "Fraunces", "Instrument Serif", "DM Serif Display", "Bodoni Moda",
  "Libre Baskerville", "Syne", "Unbounded", "Bricolage Grotesque", "Cormorant Garamond",
  "Space Grotesk", "Manrope", "Outfit", "Sora", "Archivo", "Inter Tight",
  "Plus Jakarta Sans", "DM Sans", "IBM Plex Sans", "Atkinson Hyperlegible",
  "JetBrains Mono", "IBM Plex Mono", "Space Mono",
]);
// Inter is deliberately not loaded; Inter Tight is the same design set tighter.
const SUBSTITUTE = { Inter: "Inter Tight" };
const resolve = (f) => SUBSTITUTE[f] ?? f;

const products = read("products.csv").map((r) => ({
  type: r["Product Type"],
  keywords: r["Keywords"].split(",").map((k) => k.trim()).filter(Boolean),
  style: r["Primary Style Recommendation"],
  pattern: r["Landing Page Pattern"],
  considerations: r["Key Considerations"],
}));

const colors = Object.fromEntries(
  read("colors.csv").map((r) => [
    r["Product Type"],
    {
      primary: r["Primary"], accent: r["Accent"], background: r["Background"],
      foreground: r["Foreground"], card: r["Card"], muted: r["Muted"],
      mutedForeground: r["Muted Foreground"], border: r["Border"], notes: r["Notes"],
    },
  ]),
);

const pairings = read("typography.csv")
  .map((r) => ({
    name: r["Font Pairing Name"],
    heading: resolve(r["Heading Font"]),
    body: resolve(r["Body Font"]),
    mood: r["Mood/Style Keywords"].split(",").map((k) => k.trim()).filter(Boolean),
    bestFor: r["Best For"],
  }))
  // Both faces must be served, and they must differ: substituting Inter Tight
  // for Inter collapsed several pairings into the same family twice, which is
  // not a pairing and would have been recommended as one.
  .filter((p) => LOADED.has(p.heading) && LOADED.has(p.body) && p.heading !== p.body);

const banner = `// GENERATED by scripts/build-uiux-data.mjs - do not edit by hand.
//
// Extracted from the ui-ux-pro-max skill (MIT):
// https://github.com/nextlevelbuilder/ui-ux-pro-max-skill
//
// ${products.length} product types, ${Object.keys(colors).length} palettes, ${pairings.length} font pairings
// (of 74; the rest name faces the preview does not load).
`;

writeFileSync(
  OUT,
  `${banner}
export type ProductRule = {
  type: string;
  keywords: string[];
  style: string;
  pattern: string;
  considerations: string;
};

export type Palette = {
  primary: string; accent: string; background: string; foreground: string;
  card: string; muted: string; mutedForeground: string; border: string; notes: string;
};

export type Pairing = { name: string; heading: string; body: string; mood: string[]; bestFor: string };

export const PRODUCT_RULES: ProductRule[] = ${JSON.stringify(products, null, 1)};

export const PALETTES: Record<string, Palette> = ${JSON.stringify(colors, null, 1)};

export const PAIRINGS: Pairing[] = ${JSON.stringify(pairings, null, 1)};
`,
);

console.log(`wrote ${OUT}`);
console.log(`  ${products.length} product rules`);
console.log(`  ${Object.keys(colors).length} palettes`);
console.log(`  ${pairings.length} usable font pairings (of 74)`);
