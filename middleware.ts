import { createServerClient } from "@supabase/ssr";
import { NextResponse, type NextRequest } from "next/server";
import { SUPABASE_ANON_KEY, SUPABASE_URL, isAuthEnabled } from "@/lib/supabase/config";

/** Refreshes the Supabase session cookie so server routes see a live user. */
export async function middleware(request: NextRequest) {
  if (!isAuthEnabled) return NextResponse.next();

  let response = NextResponse.next({ request });

  const supabase = createServerClient(SUPABASE_URL, SUPABASE_ANON_KEY, {
    cookies: {
      getAll: () => request.cookies.getAll(),
      setAll: (list) => {
        for (const { name, value } of list) request.cookies.set(name, value);
        response = NextResponse.next({ request });
        for (const { name, value, options } of list) response.cookies.set(name, value, options);
      },
    },
  });

  try {
    await supabase.auth.getUser();
  } catch (err) {
    // An auth outage must not take the app down.
    console.error("[auth] session refresh failed:", err instanceof Error ? err.message : err);
  }

  return response;
}

export const config = {
  matcher: ["/((?!_next/static|_next/image|favicon.ico|.*\\.(?:svg|png|jpg|jpeg|gif|webp)$).*)"],
};
